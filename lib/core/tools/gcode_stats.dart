/// G-code inspection helpers for module 06 (read-only metadata parsing).
///
/// Parses the standard metadata comments that PrusaSlicer/Cura/OrcaSlicer
/// emit. G-code is never executed or sent anywhere.
library;

class GcodeStats {
  const GcodeStats({
    required this.layerCount,
    required this.filamentMeters,
    required this.estimatedSeconds,
    required this.slicer,
    required this.lineCount,
  });

  final int layerCount;

  /// Metres of filament for the first extruder, if reported.
  final double? filamentMeters;

  /// Estimated print time in seconds, if the slicer reported it.
  final int? estimatedSeconds;

  final String? slicer;
  final int lineCount;

  String get estimatedTimeText {
    final seconds = estimatedSeconds;
    if (seconds == null) return 'not reported';
    final h = seconds ~/ 3600;
    final m = (seconds % 3600) ~/ 60;
    final s = seconds % 60;
    return '${h}h ${m}m ${s}s';
  }
}

GcodeStats parseGcodeStats(String gcode) {
  var layers = 0;
  var lines = 0;
  double? filamentMeters;
  int? estimatedSeconds;
  String? slicer;

  final estimatedTimeRegex = RegExp(
      r'estimated printing time.*?=\s*(?:(\d+)h)?\s*(?:(\d+)m)?\s*(?:(\d+)s)?',
      caseSensitive: false);
  final filamentRegex =
      RegExp(r'filament used \[mm\].*?=\s*([0-9.]+)', caseSensitive: false);

  for (final line in gcode.split('\n')) {
    lines++;
    final trimmed = line.trim();
    if (!trimmed.startsWith(';')) continue;
    if (trimmed.toLowerCase().contains('generated by') ||
        trimmed.toLowerCase().contains('sliced by')) {
      slicer ??= trimmed;
    }
    final layerMarker = RegExp(r'^;\s*LAYER:', caseSensitive: false);
    if (layerMarker.hasMatch(trimmed)) {
      layers++;
      continue;
    }
    final filamentMatch = filamentRegex.firstMatch(trimmed);
    if (filamentMatch != null) {
      // Slicer metadata is printed in millimeters.
      final mm = double.tryParse(filamentMatch.group(1)!);
      filamentMeters = mm == null ? filamentMeters : mm / 1000;
      continue;
    }
    final timeMatch = estimatedTimeRegex.firstMatch(trimmed);
    if (timeMatch != null) {
      final h = int.tryParse(timeMatch.group(1) ?? '0') ?? 0;
      final m = int.tryParse(timeMatch.group(2) ?? '0') ?? 0;
      final s = int.tryParse(timeMatch.group(3) ?? '0') ?? 0;
      estimatedSeconds = h * 3600 + m * 60 + s;
    }
  }
  return GcodeStats(
    layerCount: layers,
    filamentMeters: filamentMeters,
    estimatedSeconds: estimatedSeconds,
    slicer: slicer,
    lineCount: lines,
  );
}

class FilamentCalc {
  const FilamentCalc({
    required this.lengthMeters,
    required this.massGrams,
    required this.volumeCm3,
  });

  final double lengthMeters;
  final double massGrams;
  final double volumeCm3;
}

/// Filament conversions for 1.75 mm and 2.85 mm diameters.
/// volume(cᴍ³) = length(mm) × π × r² / 1000.
double filamentVolumeCm3(double diameterMm, double lengthMeters) {
  final radiusMm = diameterMm / 2;
  final lengthMm = lengthMeters * 1000;
  return lengthMm * 3.141592653589793 * radiusMm * radiusMm / 1000;
}

double filamentLengthMeters(double diameterMm, double volumeCm3) {
  final radiusMm = diameterMm / 2;
  final volumeMm3 = volumeCm3 * 1000;
  return volumeMm3 / (3.141592653589793 * radiusMm * radiusMm) / 1000;
}

/// PLA 1.24, PETG 1.27, ABS 1.04, TPU 1.21 g/cᴍ³ (indicative table).
double filamentDensityGPerCm3(String material) {
  switch (material.toUpperCase()) {
    case 'PLA':
      return 1.24;
    case 'PETG':
      return 1.27;
    case 'ABS':
      return 1.04;
    case 'ASA':
      return 1.07;
    case 'TPU':
      return 1.21;
    case 'NYLON':
      return 1.14;
    default:
      return 1.24;
  }
}

FilamentCalc filamentFromLength(
    double diameterMm, String material, double lengthMeters) {
  final volume = filamentVolumeCm3(diameterMm, lengthMeters);
  return FilamentCalc(
    lengthMeters: lengthMeters,
    massGrams: volume * filamentDensityGPerCm3(material),
    volumeCm3: volume,
  );
}

class PrintCostResult {
  const PrintCostResult({
    required this.materialCost,
    required this.energyCost,
    required this.total,
  });

  final double materialCost;
  final double energyCost;
  final double total;
}

/// Total print cost = filament (price/kg) + energy (P × h × price).
PrintCostResult printCost({
  required double massGrams,
  required double pricePerKg,
  required double printerWatt,
  required double hours,
  required double energyPricePerKwh,
}) {
  final material = massGrams / 1000 * pricePerKg;
  final energy = printerWatt * hours / 1000 * energyPricePerKwh;
  return PrintCostResult(
    materialCost: material,
    energyCost: energy,
    total: material + energy,
  );
}
